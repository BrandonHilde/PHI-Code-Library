#!/usr/bin/env python3
"""Generates libs/web/js/casemap.phi: Unicode case mapping and the general categories RegExp's \\p{..} needs,
as compact tables, from Python's own Unicode database.

    python tools/web/js_gen_casemap.py
"""
import os
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, '..', '..', 'libs', 'web', 'js', 'casemap.phi'))


def simple_map(fn):
    """(first, last, stride, delta) runs of the code points fn maps to one other code point."""
    pairs = []
    for cp in range(0x80, 0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        m = fn(chr(cp))
        if len(m) == 1 and ord(m) != cp:
            pairs.append((cp, ord(m) - cp))
    runs = []
    i = 0
    while i < len(pairs):
        cp, delta = pairs[i]
        stride = 1
        j = i + 1
        if j < len(pairs) and pairs[j][1] == delta and pairs[j][0] - cp in (1, 2):
            stride = pairs[j][0] - cp
            while j < len(pairs) and pairs[j][1] == delta and pairs[j][0] - pairs[j - 1][0] == stride:
                j += 1
        runs.append((cp, pairs[j - 1][0], stride, delta & 0xFFFFFFFF))
        i = j
    return runs


def specials(fn):
    """Code points whose mapping is more than one: (cp, c1, c2, c3)."""
    out = []
    for cp in range(0x80, 0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        m = fn(chr(cp))
        if len(m) > 1:
            c = [ord(x) for x in m] + [0, 0]
            out.append((cp, c[0], c[1], c[2]))
    return out


def category_ranges(want):
    runs = []
    start = None
    for cp in range(0x80, 0x110000):
        inside = unicodedata.category(chr(cp)) in want
        if inside and start is None:
            start = cp
        elif not inside and start is not None:
            runs.append((start, cp - 1))
            start = None
    if start is not None:
        runs.append((start, 0x10FFFF))
    return runs


def table(name, rows):
    flat = [x for row in rows for x in row]
    assert len(flat) <= 16384, name
    lines = [f'\tu32 {name}:']
    for i in range(0, len(flat), 16):
        lines.append('\t\t' + ' '.join(hex(x) for x in flat[i:i + 16]))
    lines[-1] += ';'
    return '\n'.join(lines) + '\n'


CATEGORIES = [
    ('cat_l', {'Lu', 'Ll', 'Lt', 'Lm', 'Lo'}),
    ('cat_lu', {'Lu'}),
    ('cat_ll', {'Ll'}),
    ('cat_n', {'Nd', 'Nl', 'No'}),
    ('cat_nd', {'Nd'}),
    ('cat_p', {'Pc', 'Pd', 'Ps', 'Pe', 'Pi', 'Pf', 'Po'}),
    ('cat_s', {'Sm', 'Sc', 'Sk', 'So'}),
    ('cat_z', {'Zs', 'Zl', 'Zp'}),
]

parts = [
    f'# Generated by tools/js_gen_casemap.py, from Unicode {unicodedata.unidata_version}. Do not edit.\n'
    '# Case maps past ASCII: runs of (first, last, stride, delta), and specials of (code point, up to three\n'
    '# it becomes). Categories: (first, last) past ASCII.\n\nphi.JsCaseData:Library\n{\n',
    table('upper_runs', simple_map(str.upper)),
    table('lower_runs', simple_map(str.lower)),
    table('upper_special', specials(str.upper)),
    table('lower_special', specials(str.lower)),
]
for name, want in CATEGORIES:
    parts.append(table(name, category_ranges(want)))
parts.append('}\n')
with open(OUT, 'w', newline='\n') as f:
    f.write(''.join(parts))
print(OUT, os.path.getsize(OUT), 'bytes')
