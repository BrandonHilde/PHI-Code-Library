#!/usr/bin/env python3
"""Writes libs/web/js/unicode.phi: which code points can start and continue a JS identifier.

It reads ID_Start and ID_Continue from Unicode's own DerivedCoreProperties.txt, kept at
libs/web/tests/js/unicode/ (from https://www.unicode.org/Public/UCD/latest/ucd/).

    python tools/web/js_gen_unicode.py       (from the repository root)
"""
import os
import re
import sys


def read_properties(path):
    props = {'ID_Start': [], 'ID_Continue': []}
    version = '?'
    with open(path, encoding='utf-8') as f:
        for line in f:
            m = re.match(r'# DerivedCoreProperties-([\d.]+)\.txt', line)
            if m:
                version = m.group(1)
            m = re.match(r'([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*; (ID_Start|ID_Continue)\b', line)
            if m:
                lo = int(m.group(1), 16)
                hi = int(m.group(2) or m.group(1), 16)
                props[m.group(3)].append((lo, hi))
    return props, version


def merged(rs):
    out = []
    for lo, hi in sorted(rs):
        if hi < 0x80:
            continue
        lo = max(lo, 0x80)
        if out and lo <= out[-1][1] + 1:
            out[-1] = (out[-1][0], max(hi, out[-1][1]))
        else:
            out.append((lo, hi))
    return out


def table(name, rs):
    lines = []
    row = []
    for lo, hi in rs:
        row.append('0x%X 0x%X' % (lo, hi))
        if len(row) == 8:
            lines.append('\t\t' + ' '.join(row))
            row = []
    if row:
        lines.append('\t\t' + ' '.join(row))
    return '\tu32 %s:\n%s;\n' % (name, '\n'.join(lines))


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    source = os.path.join(here, '..', '..', 'libs', 'web', 'tests', 'js', 'unicode', 'DerivedCoreProperties.txt')
    path = os.path.join(here, '..', '..', 'libs', 'web', 'js', 'unicode.phi')
    props, version = read_properties(source)
    start = merged(props['ID_Start'])
    cont = merged(props['ID_Continue'])
    with open(path, 'w', newline='\n') as f:
        f.write('# Generated by tools/js_gen_unicode.py, from Unicode %s. Do not edit.\n' % version)
        f.write('# Which code points past ASCII can start and continue an identifier: pairs, first and\n')
        f.write('# last of a range, in order.\n\n')
        f.write('phi.JsUnicode:Library\n{\n')
        f.write(table('id_start', start))
        f.write('\n')
        f.write(table('id_continue', cont))
        f.write('''
	[InTable: ptr<u32> t: 0; int pairs: 0; u32 c: 0;]
		int lo: 0;
		int hi: pairs - 1;
		while lo <= hi
			int mid: (lo + hi) / 2;
			if c < t:(mid * 2)
				hi is mid - 1;
			;;
			elif c > t:(mid * 2 + 1)
				lo is mid + 1;
			;;
			else
				return true;
			;;
		;;
	[end: false]

	[IsIdStart: u32 c: 0;]
	[end: (InTable: addr id_start id_start.len / 2 c)]

	[IsIdContinue: u32 c: 0;]
	[end: (InTable: addr id_continue id_continue.len / 2 c)]
}
''')
    print(path, version, len(start), len(cont))


if __name__ == '__main__':
    sys.exit(main())
