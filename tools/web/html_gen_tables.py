def const_name(name):
    return name.upper().replace("-", "_").replace(":", "_")


def gen_tags():
    # elements first, the most common at the front; the order means nothing else
    names = []

    def add(group):
        for n in group:
            if n not in names:
                names.append(n)

    add("div span a p li td tr img b i ul table tbody th input br".split())
    add(SPECIAL)
    add(FORMATTING)
    add(OTHER)
    add(BODY_START)
    add(BODY_END)
    add(FOREIGN_NAMES)
    element_count = len(names)

    def flags_of(n):
        f = 0
        for group, bit in (
            (SPECIAL, F_SPECIAL), (SCOPE, F_SCOPE), (TABLE_SCOPE, F_TABLE), (IMPLIED, F_IMPLIED),
            (THOROUGH, F_THOROUGH), (FORMATTING, F_FORMAT), (VOID, F_VOID), (RAW, F_RAWTEXT),
            (RESET, F_RESET), (BREAKOUT, F_BREAKOUT), (BODY_START, F_BODY_START), (BODY_END, F_BODY_END),
        ):
            if n in group:
                f |= bit
        if n in ("ol", "ul"):
            f |= F_LIST
        if n == "button":
            f |= F_BUTTON
        if n in SPECIAL and n not in ("address", "div", "p"):
            f |= F_LI_STOP
        return f

    # the mixed-case names follow: one number each, for the lowercase spelling
    adjust = []
    kinds = {}
    for n in SVG_TAGS:
        adjust.append(n)
        kinds[n] = 1
    for n in SVG_ATTRS:
        if n in kinds:
            kinds[n] |= 2
        else:
            adjust.append(n)
            kinds[n] = 2
    for n in adjust:
        if n.lower() in names:
            raise SystemExit("%s is already a name" % n)

    # the numbers: 0 is any name we don't know
    number = {}
    for i, n in enumerate(names):
        number[n] = i + 1
    adj_first = element_count + 1
    adj_last = adj_first + len(adjust) - 1
    fa_first = adj_last + 1
    fa_last = fa_first + len(FOREIGN_ATTRS) - 1
    definition_url = fa_last + 1
    atom_count = definition_url + 1

    # codes of what's on the stack that isn't an HTML element, after every name's number
    foreign = [
        ("K_SVG", 0), ("K_SVG_FOREIGNOBJECT", F_HTML_IP), ("K_SVG_DESC", F_HTML_IP), ("K_SVG_TITLE", F_HTML_IP),
        ("K_MATH", 0), ("K_MATH_MI", F_MATH_TEXT), ("K_MATH_MO", F_MATH_TEXT), ("K_MATH_MN", F_MATH_TEXT),
        ("K_MATH_MS", F_MATH_TEXT), ("K_MATH_MTEXT", F_MATH_TEXT), ("K_MATH_ANNOTATION_XML", 0),
    ]
    code_count = atom_count + len(foreign)

    out = []
    w = out.append
    w("# GENERATED by tools/html_gen_tables.py: do not edit.")
    w("#")
    w("# The numbers WlAtom.tag holds for names the HTML parser knows. An element's name has one of the")
    w("# numbers below LAST_ELEMENT; the mixed-case SVG names and the attributes foreign content adjusts")
    w("# have numbers after those, and a name nobody knows has 0. HtmlTags.Start hangs them on the atoms.")
    w("#")
    w("# An element on the parser's stack has a code: its name's number if it's an HTML element, one of")
    w("# the K_ numbers if it isn't. Flags tell what the spec's lists say about each code.")
    w("")
    w("use core.atoms;")
    w("")
    w("phi.HtmlTag:Library")
    w("{")
    for n in names:
        w("\tconst u32 %s: %d;" % (const_name(n), number[n]))
    w("")
    w("\tconst u32 FOREIGNOBJECT: %d;" % (adj_first + adjust.index("foreignObject")))
    w("\tconst u32 LAST_ELEMENT: %d;" % element_count)
    w("\tconst u32 ADJUST_FIRST: %d;" % adj_first)
    w("\tconst u32 ADJUST_LAST: %d;" % adj_last)
    w("\tconst u32 FOREIGN_ATTR_FIRST: %d;" % fa_first)
    w("\tconst u32 FOREIGN_ATTR_LAST: %d;" % fa_last)
    w("\tconst u32 DEFINITIONURL: %d;" % definition_url)
    w("\tconst u32 ATOM_COUNT: %d;" % atom_count)
    w("")
    for i, (name, _) in enumerate(foreign):
        w("\tconst u32 %s: %d;" % (name, atom_count + i))
    w("\tconst u32 CODE_COUNT: %d;" % code_count)
    w("")
    for name, bit in (
        ("F_SPECIAL", F_SPECIAL), ("F_SCOPE", F_SCOPE), ("F_LIST", F_LIST), ("F_BUTTON", F_BUTTON),
        ("F_TABLE", F_TABLE), ("F_IMPLIED", F_IMPLIED), ("F_THOROUGH", F_THOROUGH), ("F_FORMAT", F_FORMAT),
        ("F_VOID", F_VOID), ("F_RAWTEXT", F_RAWTEXT), ("F_RESET", F_RESET), ("F_BREAKOUT", F_BREAKOUT),
        ("F_BODY_START", F_BODY_START), ("F_BODY_END", F_BODY_END), ("F_LI_STOP", F_LI_STOP),
        ("F_MATH_TEXT", F_MATH_TEXT), ("F_HTML_IP", F_HTML_IP),
    ):
        w("\tconst u32 %s: 0x%x;" % (name, bit))
    w("")

    # the tables as text, read once by HtmlTags.Start
    el = " ".join("%s:%x" % (n, flags_of(n)) for n in names)
    w("\tptr<u8> ELEMENT_TEXT: '%s';" % el)
    w("\tptr<u8> ADJUST_TEXT: '%s';" % " ".join("%s:%d" % (n, kinds[n]) for n in adjust))
    w("\tptr<u8> FOREIGN_ATTR_TEXT: '%s';" % " ".join("%s=%s=%s" % t for t in FOREIGN_ATTRS))
    w("\tptr<u8> FOREIGN_CODE_FLAGS: '%s';" % " ".join("%x" % (fl | F_SPECIAL | F_SCOPE | F_LI_STOP) if fl or name == "K_MATH_ANNOTATION_XML" else "0" for name, fl in foreign))
    w("}")
    w("")
    with open(os.path.join(OUT, "tags.phi"), "w", newline="\n") as f:
        f.write("\n".join(out))
    print("tags.phi: %d elements, %d codes" % (element_count, code_count))


if __name__ == "__main__":
    gen_entities()
    gen_tags()
