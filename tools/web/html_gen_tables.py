#!/usr/bin/env python3
"""Writes libs/web/html/entities.phi and libs/web/html/tags.phi.

    python tools/web/html_gen_tables.py

entities.phi holds the named character references from Python's html.entities.html5, as one blob
of text sorted by name (built into an index the first time a reference is seen).
tags.phi holds the numbering of names the parser treats specially, and what it knows about each.
The tables come from the WHATWG parsing spec, section 13.2.4 and 13.2.6.
"""
import html.entities
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "libs", "web", "html")

# ---- named character references


def gen_entities():
    table = html.entities.html5
    if len(table) != 2231:
        raise SystemExit("expected 2231 entries, got %d" % len(table))
    names = sorted(table, key=lambda n: n.encode("ascii"))
    lines = []
    longest = 0
    for name in names:
        cps = ",".join("%x" % ord(c) for c in table[name])
        lines.append("%s:%s" % (name, cps))
        longest = max(longest, len(name))
    blob = "\n".join(lines)
    with open(os.path.join(OUT, "entities.phi"), "w", newline="\n") as f:
        f.write(
            "# GENERATED by tools/html_gen_tables.py from Python's html.entities.html5: do not edit.\n"
            "#\n"
            "# Every named character reference, as lines of NAME:HEX[,HEX] sorted by the bytes of NAME.\n"
            "# Names that end in ';' and those that don't are separate entries, as in the spec's table.\n"
            "\n"
            "phi.HtmlEntityData:Library\n"
            "{\n"
            "\tconst u32 COUNT: %d;\n"
            "\tconst u32 LONGEST: %d;\n"
            "\n"
            "\tptr<u8> blob: '%s';\n"
            "}\n" % (len(names), longest, blob)
        )
    print("entities.phi: %d names, blob %d bytes, longest name %d" % (len(names), len(blob), longest))


# ---- tag names

F_SPECIAL = 0x001       # the spec's "special" category
F_SCOPE = 0x002         # stops "in scope" (and so list item and button scope too)
F_LIST = 0x004          # also stops "in list item scope": ol, ul
F_BUTTON = 0x008        # also stops "in button scope": button
F_TABLE = 0x010         # stops "in table scope"
F_IMPLIED = 0x020       # popped by generate implied end tags
F_THOROUGH = 0x040      # popped by generate all implied end tags thoroughly
F_FORMAT = 0x080        # the spec's formatting category
F_VOID = 0x100          # serializes as void
F_RAWTEXT = 0x200       # its text serializes literally
F_RESET = 0x400         # decides "reset the insertion mode appropriately"
F_BREAKOUT = 0x800      # a start tag of this name leaves foreign content
F_BODY_START = 0x1000   # a start tag of this name has its own entry "in body"
F_BODY_END = 0x2000     # an end tag of this name has its own entry "in body"
F_LI_STOP = 0x4000      # special, but not address, div or p: stops the search for li, dd and dt
F_MATH_TEXT = 0x8000    # (foreign codes) a MathML text integration point
F_HTML_IP = 0x10000     # (foreign codes) always an HTML integration point

